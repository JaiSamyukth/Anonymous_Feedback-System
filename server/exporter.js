'use strict';
/** Builds a filtered, multi-sheet Excel report. */
const ExcelJS = require('exceljs');
const reports = require('./reports');
const { toRoman } = require('./util');

const BRAND = 'FF4338CA';

function styleHeader(ws) {
  const row = ws.getRow(1);
  row.font = { bold: true, color: { argb: 'FFFFFFFF' } };
  row.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: BRAND } };
  row.alignment = { vertical: 'middle' };
  row.height = 22;
  ws.views = [{ state: 'frozen', ySplit: 1 }];
  ws.autoFilter = { from: { row: 1, column: 1 }, to: { row: 1, column: ws.columnCount } };
}

function scoreFill(cell, v) {
  if (typeof v !== 'number') return;
  const color = v >= 8 ? 'FFD1FAE5' : v >= 6 ? 'FFFEF3C7' : 'FFFEE2E2';
  cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: color } };
}

function sheet(wb, name, columns, rows, scoreKeys = ['average']) {
  const ws = wb.addWorksheet(name);
  ws.columns = columns.map((c) => ({ header: c.header, key: c.key, width: c.width || 14, style: c.numFmt ? { numFmt: c.numFmt } : {} }));
  for (const r of rows) {
    const added = ws.addRow(r);
    for (const k of scoreKeys) {
      const col = columns.findIndex((c) => c.key === k);
      if (col >= 0) scoreFill(added.getCell(col + 1), r[k]);
    }
  }
  styleHeader(ws);
  return ws;
}

async function build(db, f, admin, { audience = 'admin' } = {}) {
  const forFaculty = audience === 'faculty';
  const minResponses = Number(db.getSetting('min_responses', '3'));
  const wb = new ExcelJS.Workbook();
  wb.creator = 'Anonymous Faculty Feedback System';
  wb.created = new Date();

  const w = reports.where(db, f);
  const cycle = w.cycle ? db.get('SELECT * FROM cycles WHERE id = ?', w.cycle) : null;
  const name = (t, id) => (id ? db.get(`SELECT * FROM ${t} WHERE id = ?`, id) : null);
  const dept = name('departments', f.department_id);
  const fac = name('faculty', f.faculty_id);
  const sub = name('subjects', f.subject_id);
  const questions = db.all('SELECT id, position, short, text FROM questions ORDER BY position, id');

  // Info sheet
  const info = wb.addWorksheet('Report');
  info.columns = [{ width: 26 }, { width: 60 }];
  info.addRow([db.getSetting('institution_name')]).font = { bold: true, size: 16, color: { argb: BRAND } };
  info.addRow(['Faculty Feedback Report']).font = { bold: true, size: 12 };
  info.addRow([]);
  const meta = [
    ['Feedback cycle', cycle ? cycle.name : 'All cycles'],
    ['Academic year', f.academic_year || cycle?.academic_year || 'All'],
    ['Department', dept ? `${dept.code} — ${dept.name}` : 'All departments'],
    ['Year', f.year ? toRoman(f.year) : 'All'],
    ['Semester', f.semester ? toRoman(f.semester) : 'All'],
    ['Section', f.section || 'All'],
    ['Faculty', fac ? `${fac.name} (${fac.staff_id})` : 'All'],
    ['Subject', sub ? `${sub.name} (${sub.code})` : 'All'],
    ['Generated', new Date().toLocaleString('en-IN')],
    ['Generated by', admin.name],
    ['Rating scale', '1 (lowest) to 10 (highest)'],
    ['Anonymity', 'Responses contain no student identity. Register numbers are never stored with ratings.'],
  ];
  for (const m of meta) {
    const r = info.addRow(m);
    r.getCell(1).font = { bold: true };
  }

  // Faculty exports never include groups small enough to single out students.
  const g = (group) => reports.grouped(db, f, group).rows.filter((r) => !forFaculty || r.responses >= minResponses);
  const statCols = [
    { header: 'Responses', key: 'responses', width: 12 },
    { header: 'Average', key: 'average', width: 11, numFmt: '0.00' },
    { header: 'Lowest', key: 'min', width: 10, numFmt: '0.00' },
    { header: 'Highest', key: 'max', width: 10, numFmt: '0.00' },
    { header: '≥ 8 (Excellent)', key: 'band_high', width: 15 },
    { header: '6 – 8 (Good)', key: 'band_mid', width: 13 },
    { header: '< 6 (Needs focus)', key: 'band_low', width: 17 },
  ];

  if (!forFaculty) sheet(wb, 'Faculty-wise', [
    { header: 'Faculty', key: 'label', width: 28 },
    { header: 'Staff ID', key: 'sub', width: 12 },
    { header: 'Designation', key: 'designation', width: 22 },
    { header: 'Department', key: 'department_code', width: 12 },
    { header: 'Subjects', key: 'subjects', width: 10 },
    ...statCols,
  ], g('faculty'));

  sheet(wb, 'Subject-wise', [
    { header: 'Subject', key: 'label', width: 30 },
    { header: 'Code', key: 'sub', width: 12 },
    { header: 'Department', key: 'department_code', width: 12 },
    { header: 'Faculty', key: 'faculty_names', width: 34 },
    ...statCols,
  ], g('subject'));

  sheet(wb, 'Class-wise', [
    { header: 'Class', key: 'label', width: 34 },
    { header: 'Faculty rated', key: 'faculty_count', width: 13 },
    ...statCols,
  ], g('class'));

  if (!forFaculty) sheet(wb, 'Department-wise', [
    { header: 'Department', key: 'label', width: 14 },
    { header: 'Name', key: 'sub', width: 40 },
    ...statCols,
  ], g('department'));

  sheet(wb, 'Question-wise', [
    { header: '#', key: 'position', width: 5 },
    { header: 'Question', key: 'text', width: 80 },
    { header: 'Average', key: 'average', width: 11, numFmt: '0.00' },
    { header: 'Lowest', key: 'min', width: 10 },
    { header: 'Highest', key: 'max', width: 10 },
  ], g('question'));

  sheet(wb, 'Year-wise', [{ header: 'Year', key: 'label', width: 14 }, ...statCols], g('year'));
  sheet(wb, 'Semester-wise', [{ header: 'Semester', key: 'label', width: 16 }, ...statCols], g('semester'));
  sheet(wb, 'Academic year-wise', [{ header: 'Academic year', key: 'label', width: 16 }, ...statCols], g('academic_year'));

  // Entity × question matrices (same data as the Visualize heatmaps).
  for (const [grp, title, labelHeader] of [['class', 'Class × Question', 'Class'], ['faculty', 'Faculty × Question', 'Faculty']]) {
    if (forFaculty && grp === 'faculty') continue;
    const m = reports.matrix(db, f, grp);
    const rows = m.rows.filter((r) => !forFaculty || r.responses >= minResponses);
    const qcols = m.questions.map((q) => ({ header: `Q${q.position} ${q.short || ''}`.trim(), key: `q${q.id}`, width: 12, numFmt: '0.00' }));
    sheet(wb, title, [
      { header: labelHeader, key: 'label', width: 34 },
      { header: 'Responses', key: 'responses', width: 11 },
      ...qcols,
      { header: 'Overall', key: 'average', width: 10, numFmt: '0.00' },
    ], rows.map((r) => ({ label: r.label, responses: r.responses, average: r.average, ...Object.fromEntries(m.questions.map((q) => [`q${q.id}`, r.questions[q.id] ?? null])) })),
    ['average', ...m.questions.map((q) => `q${q.id}`)]);
  }

  if (forFaculty) return wb.xlsx.writeBuffer();

  // Anonymous individual responses (no identifiers of any kind).
  const resp = reports.responses(db, f, { limit: 500, offset: 0 });
  const all = [];
  for (let off = 0; off < resp.total; off += 500) {
    const page = off === 0 ? resp : reports.responses(db, f, { limit: 500, offset: off });
    all.push(...page.rows);
  }
  const rcols = [
    { header: 'Date', key: 'submitted_on', width: 12 },
    { header: 'Department', key: 'department_code', width: 12 },
    { header: 'Year', key: 'year_r', width: 7 },
    { header: 'Sem', key: 'sem_r', width: 7 },
    { header: 'Section', key: 'section', width: 9 },
    { header: 'Faculty', key: 'faculty_name', width: 26 },
    { header: 'Subject', key: 'subject_name', width: 28 },
    ...questions.map((q) => ({ header: `Q${q.position}`, key: `q${q.id}`, width: 6 })),
    { header: 'Average', key: 'average', width: 10, numFmt: '0.00' },
    { header: 'Comment', key: 'comment', width: 50 },
  ];
  sheet(
    wb,
    'Responses (anonymous)',
    rcols,
    all.map((r) => ({
      ...r,
      year_r: toRoman(r.year),
      sem_r: toRoman(r.semester),
      ...Object.fromEntries(questions.map((q) => [`q${q.id}`, r.ratings[q.id] ?? null])),
    })),
  );

  return wb.xlsx.writeBuffer();
}

module.exports = { build };
